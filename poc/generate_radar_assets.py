#!/usr/bin/env python3
"""Pack Radar DESCRIPTION + TEXTDB into radar_assets.h.
IMAGEDB is reused from hello_assets.h (icon 55010)."""
import io
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent


def to_c_array(name: str, data: bytes) -> str:
    lines = [f"static const unsigned char {name}[] = {{"]
    hex_data = [f"0x{b:02x}" for b in data]
    for i in range(0, len(hex_data), 12):
        lines.append("    " + ", ".join(hex_data[i : i + 12]) + ",")
    lines.append("};")
    lines.append(f"static const size_t {name}_len = {len(data)};")
    return "\n".join(lines)


def texts_zip() -> bytes:
    body = (
        "1=speeduntrap\n"
        "2=Popup\n"
        "4=Page\n"
        "5=Pages\n"
        "6=Range -\n"
        "7=Range +\n"
        "39=speeduntrap\n"
        "51=speeduntrap\n"
    )
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for name in ("en-UK.txt", "en-US.txt"):
            zf.writestr(name, body)
    return buf.getvalue()


def main() -> None:
    xml = (HERE / "assets" / "radar.xml").read_bytes()
    texts = texts_zip()
    out = HERE / "radar_assets.h"
    out.write_text(
        "/* Auto-generated by generate_radar_assets.py - do not edit. */\n"
        "#ifndef RADAR_ASSETS_H\n"
        "#define RADAR_ASSETS_H\n\n"
        "#include <stddef.h>\n\n"
        + to_c_array("radar_xml", xml)
        + "\n\n"
        + to_c_array("radar_texts_zip", texts)
        + "\n\n#endif\n",
        encoding="utf-8",
    )
    print(f"wrote {out} xml={len(xml)} texts={len(texts)}")


if __name__ == "__main__":
    main()
